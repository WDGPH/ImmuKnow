// Generate ordinary validation functions; the browser never compiles schemas.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { build } from "vite";
import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standalone from "ajv/dist/standalone/index.js";

const payload = JSON.parse(readFileSync(new URL("../../immuknow/schemas/rendering-v1.json", import.meta.url)));
const report = JSON.parse(readFileSync(new URL("../../immuknow/templates/lib/immuknow/report-v2.json", import.meta.url)));
const ajv = new Ajv2020({ code: { source: true, lines: true } });
for (const keyword of ["x-evaluator", "x-adjustable", "x-components"]) ajv.addKeyword(keyword);
addFormats(ajv);
ajv.addSchema(payload);
ajv.addSchema(report);
const code = "// Generated by scripts/prepare-contracts.mjs. Edit the shared JSON schemas.\n" +
  standalone(ajv, { validatePayload: payload.$id, validateReport: report.$id });
const output = new URL("../generated/render-contract.cjs", import.meta.url);
mkdirSync(new URL("../generated/", import.meta.url), { recursive: true });
writeFileSync(output, code);
// Bundle the validator's runtime helpers into a browser module. Dev workers
// load this directly, without the CommonJS conversion in a production build.
const [bundle] = await build({
  configFile: false,
  root: fileURLToPath(new URL("../", import.meta.url)),
  logLevel: "error",
  build: {
    write: false,
    minify: false,
    lib: { entry: fileURLToPath(output), formats: ["es"] },
  },
});
writeFileSync(new URL("../generated/render-contract.js", import.meta.url), bundle.output[0].code);
